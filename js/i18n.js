function translateDOM(root) {
  if (!IS_EN) return;
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walk.nextNode(); n; n = walk.nextNode()) {
    const raw = n.nodeValue, key = raw.replace(/\s+/g, ' ').trim();
    if (key && EN[key] !== undefined) { const lead = raw.match(/^\s*/)[0], tail = raw.match(/\s*$/)[0]; n.nodeValue = lead + EN[key] + tail; }
  }
  root.querySelectorAll('[placeholder],[aria-label],[title],[alt]').forEach(el => {
    for (const a of ['placeholder', 'aria-label', 'title', 'alt']) { const v = el.getAttribute(a); if (v && EN[v.trim()] !== undefined) el.setAttribute(a, EN[v.trim()]); }
  });
}
